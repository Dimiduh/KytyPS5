#ifndef EMULATOR_SRC_GRAPHICS_HOST_GPU_VULKANRECORDING_H_
#define EMULATOR_SRC_GRAPHICS_HOST_GPU_VULKANRECORDING_H_

#include <cstddef>
#include <cstdint>

// Vulkan command recording on a thread of its own. The thread that translates guest GPU commands
// (the producer) spends a large part of its time inside the driver: every vkCmd* validates,
// encodes and sometimes allocates there. With a ProducerScope, that thread's command-buffer
// commands are copied into a stream instead, arguments and all, and a recording thread replays
// them into the same command buffers in the same order. The producer stays the only owner of
// the renderer's state; the recording thread only makes the calls.
//
// Install replaces the entries of Vulkan-Hpp's default dispatcher by thunks (generated by
// generateVulkanRecording.py), so no call site changes:
// - a vkCmd* whose arguments can be copied is queued, as are the begin and the end of a command
//   buffer and the few host calls that must keep their place among the commands;
// - any other call on the producer's thread first waits until the recording thread has replayed
//   everything queued (it may depend on it, or use the same command pool), unless it cannot
//   depend on it (queries, waits, new objects);
// - on every other thread the thunks call the driver as before.
//
// The design follows the Vulkan recording of chenxiao07's KytyPS5 fork (src/local/
// vulkan-recording.*, branch experiment/perf-40fps-20260926).
namespace Libs::Graphics::VulkanRecording {

// After the default dispatcher was initialized for the device, before any command is recorded.
void Install();

// The calling thread becomes a producer for the scope's lifetime: its recording thread starts
// here and ends, drained, with the scope. One scope per thread.
class ProducerScope {
public:
	ProducerScope();
	~ProducerScope();
	ProducerScope(const ProducerScope&)            = delete;
	ProducerScope& operator=(const ProducerScope&) = delete;
};

// The calling thread's commands are being queued (a producer with the vulkan_recording switch
// on).
[[nodiscard]] bool Recording();

// Returns once the recording thread has replayed everything the calling thread queued. Needed
// before handing the thread's command buffers to code that calls the driver past the
// dispatcher (an upscaler library) or to another thread. Does not wait for the GPU.
void Drain();

// Queues `function(data)` to run on the recording thread after everything queued so far, with a
// copy of the `size` bytes at `data` (trivially copyable, at most a few kilobytes). With
// `publish` the recording thread sees it at once instead of with the next batch: for work other
// threads wait for, such as handing a command buffer to the submission thread. False (nothing
// queued) when the calling thread does not record; the caller then drains and runs it itself.
[[nodiscard]] bool EnqueueOrdered(void (*function)(const void*), const void* data, size_t size,
                                  bool publish);

} // namespace Libs::Graphics::VulkanRecording

#endif /* EMULATOR_SRC_GRAPHICS_HOST_GPU_VULKANRECORDING_H_ */
